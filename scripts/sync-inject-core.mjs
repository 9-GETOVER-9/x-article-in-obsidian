#!/usr/bin/env node
/**
 * Vendor the inject-core browser runner bundle for distributed Obsidian builds.
 *
 * The source of truth lives in the sibling x-article-workspace repo:
 *   packages/inject-core/dist/inject-core-runner.iife.js
 *
 * This script writes a tiny TypeScript wrapper exporting the bundle as a string
 * so the plugin can pass it to Playwright MCP browser_evaluate without relying
 * on a sibling repo on the user's machine.
 */
import { createHash } from "node:crypto";
import { execSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, "..");

const args = process.argv.slice(2);
const wsIdx = args.indexOf("--workspace");
const wsArg = wsIdx >= 0 ? args[wsIdx + 1] : null;
const CHECK = args.includes("--check");
const SKIP_BUILD = args.includes("--skip-build");

const WORKSPACE = resolve(REPO_ROOT, wsArg || "../x-article-workspace");
const BUNDLE_SRC = resolve(WORKSPACE, "packages/inject-core/dist/inject-core-runner.iife.js");
const VENDOR_DIR = resolve(REPO_ROOT, "src/vendor/x-article-inject-core");
const VENDOR_PATH = resolve(VENDOR_DIR, "runner.ts");

if (!SKIP_BUILD) {
  try {
    execSync("pnpm -C packages/inject-core build", {
      cwd: WORKSPACE,
      stdio: CHECK ? "pipe" : "inherit",
    });
  } catch (error) {
    console.error("✗ failed to build inject-core browser bundle");
    if (CHECK && error && typeof error === "object" && "stdout" in error) {
      process.stderr.write(String(error.stdout || ""));
      process.stderr.write(String(error.stderr || ""));
    }
    process.exit(1);
  }
}

if (!existsSync(BUNDLE_SRC)) {
  console.error(`✗ inject-core browser bundle not found: ${BUNDLE_SRC}`);
  console.error("  run this script without --skip-build, or pass --workspace <path>.");
  process.exit(1);
}

const bundle = readFileSync(BUNDLE_SRC, "utf-8").trimEnd() + "\n";
const sha = createHash("sha256").update(bundle).digest("hex");
const out = `// AUTO-GENERATED by scripts/sync-inject-core.mjs — do not edit by hand.
// Source: <workspace>/packages/inject-core/dist/inject-core-runner.iife.js
// To update: bump the upstream workspace, then run \`npm run sync:inject-core\`.

export const INJECT_CORE_RUNNER_SHA256 = "${sha}";

export const INJECT_CORE_RUNNER_SOURCE = ${JSON.stringify(bundle)};
`;

if (CHECK) {
  if (!existsSync(VENDOR_PATH)) {
    console.error(`✗ vendor file missing: ${relative(REPO_ROOT, VENDOR_PATH)}`);
    process.exit(2);
  }
  const existing = readFileSync(VENDOR_PATH, "utf-8");
  if (existing === out) {
    console.log(`✓ inject-core vendor up to date (${sha.slice(0, 16)})`);
    process.exit(0);
  }
  console.error("✗ inject-core vendor is stale. Run: npm run sync:inject-core");
  console.error(`  expected sha256[0..16]: ${sha.slice(0, 16)}`);
  process.exit(1);
}

mkdirSync(VENDOR_DIR, { recursive: true });
writeFileSync(VENDOR_PATH, out, "utf-8");
console.log(
  `✓ wrote ${relative(REPO_ROOT, VENDOR_PATH)} (${bundle.length} bytes, sha256[0..16]=${sha.slice(0, 16)})`,
);
